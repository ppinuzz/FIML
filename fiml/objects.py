@dataclass
class GPData:
    beta: jax.Array
    sol: jax.Array
    covariance_theta_blocks: tuple[jax.Array, ...]
    covariance_beta_blocks: tuple[jax.Array, ...]
    #case_ids: tuple[str, ...]
    
    def __post_init__(self):
        self.beta = jnp.asarray(self.beta)
        self.sol = jnp.asarray(self.sol)


@dataclass
class GaussianProcess:
    data: GPData
    kernel: Callable
    log_likelihood: Callable
    beta_mean: jax.Array
    covariance: jax.Array
    parameters: tuple[float, ...]
    
    def __post_init__(self):
        self.likelihood = lambda P: jnp.exp(self.likelihood(P))
        # must be finite, symmetric, and positive definite
        aux.check_covariance_matrix(self.covariance)
        


