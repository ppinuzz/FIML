@dataclass
class SamplingResult:
    theta_orig: jax.Array
    solution_orig: jax.Array
    max_res_orig: jax.Array
    success_orig: jax.Array
    # only required to calculate beta from the solution
    beta_fun: InitVar[Callable]
    # will be calculated from the solution
    beta_orig: jax.Array | None = None
    # key used in random number generator
    key_random: float | None = None
    
    def __post_init__(self, beta_fun):
        self.theta_orig = jnp.asarray(self.theta_orig)
        self.solution_orig = jnp.asarray(self.solution_orig)
        self.max_res_orig = jnp.asarray(self.max_res_orig)
        self.success_orig = jnp.asarray(self.success_orig)
        if self.beta_orig is None:
            self.beta_orig = jax.vmap(lambda theta, u: beta_fun(theta, u=u),
                                    # theta is a row vector of columns => pick 
                                    # one column of theta at a time => index 1
                                    # u is ordered as a (Nx, Nt, N_samples) 
                                    # matrix => calculate beta for each sample 
                                    # solution => index 2
                                    in_axes=(1, 2),
                                    # store results in the 3rd dimension
                                    # ("one per layer")
                                    out_axes=2
                                    )(self.theta_orig, self.solution_orig)
        
        # remove failed runs (i.e. not converged or Inf/NaN in the solution)
        # NB: transpose beta since beta is (Nx, Nt), but the code expects fields
        # in the form (Nt, Nx)
        sol_good, max_res_good = fiml.handle_failed_runs(
                                                (self.solution_orig, self.max_res_orig), 
                                                self.success_orig, strategy='remove')
        self.theta = self.theta_orig[:,self.success_orig]
        self.solution = sol_good
        self.max_res = max_res_good
        #self.beta = beta_T_good.T
        self.beta = self.beta_orig[:,:,self.success_orig]
        self.success = self.success_orig[self.success_orig]
        self.N_valid = self.success.size
        
        # 1st index: time, 2nd index: space, 3rd index: sample
        if not (self.N_valid == self.solution.shape[2] == self.max_res.shape[2] == self.beta.shape[2]):
            msg = ( f'self.N_valid = {self.N_valid}\n'
                    f'sol_good.shape[0] = {self.solution.shape[2]}\n'
                    f'max_res_good.shape[0] = {self.max_res.shape[2]}\n'
                    f'beta_T_good.shape[0] = {self.beta.shape[2]}')
            raise RuntimeError('Array dimension are not matching when removing '
                               f'failed simulations from sampling\n{msg}')


@dataclass
class CostFunction:
    # covariance matrices
    C_data: float | jax.Array
    C_theta: float | jax.Array
    data: ExperimentalData
    h_theta: Callable | None = None
    theta_prior: jax.Array | None = None
    # weight of the regularisation term in cost = J_fit + W_reg * J_reg
    W_reg: float = 1.0
    # jacobian of the cost function w.r.t. theta 
    jacobian: Callable | None = None
    
    def __post_init__(self):
        if self.W_reg is None:
            # original formulation: no penalisation for regularisation term
            self.W_reg = 1
        # check that covariance matrces are finite, symmetric, and positive definite
        aux.check_covariance_matrix(self.C_data)
        aux.check_covariance_matrix(self.C_theta)
    
    def generate_theta_prior(self, N_theta):
        # does nothing if the prior is given
        if self.theta_prior is None:
            self.theta_prior = jnp.zeros(shape=(N_theta, ))
        return self.theta_prior
    
    def __call__(self, theta):
        # cost, success = fiml.cost_function(...)
        # pass data as a column vector of column vectors => (...).T has shape
        # (N,1), unravel it to pass it as (N, )
        return fiml.cost_function(theta, d=jnp.ravel(self.data.solution.T), 
                                  h_theta=self.h_theta,
                                  Cm=self.C_data, C_theta=self.C_theta,
                                  theta_prior=self.theta_prior, weight_reg=self.W_reg)


@dataclass
class FieldInversionObject:
    problem: Problem
    exp_data: dict
    beta_fun: Callable
    beta_params: dict
    beta_opts: dict
    
    cost: CostFunction | None = None
    # jacobian of the cost function w.r.t. theta only
    jacobian: Callable | None = None
    MAP: MAPResult | None = None
    prior: SamplingResult | None = None
    posterior: SamplingResult | None = None

    def __post_init__(self):
        self.N_params = self.beta_params['N_params']



