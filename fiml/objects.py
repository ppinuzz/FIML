@dataclass
class Problem:
    # mark it as a dictionary that will be unpacked and read during
    # initialisation, but not stored in the class => avoid unadvertedly 
    # modyfing the data in the dicionary
    #   Problem.x_mesh      => works
    #   Problem.mesh        => error (AttributeError)
    mesh: InitVar[dict]
    BC: dict
    # in Burgers, nu = nu0 * beta => nu_baseline = nu0
    nu_baseline: Callable
    solver_fun: Callable | None
    # optional input: if not given by the user, it will be calculated based
    # on the size of t_mesh (1 time instant => steady problem)
    STEADY: bool | None = None
    # defined DERIVED ATTRIBUTES: they're not supplied by the user to the
    # constructor, but calculated by the class
    #   init=False      not automatically generated by __init__()
    #   repr=False      no automatic string representation of the object
    #                   (as the mesh could be very big)
    x_mesh: jax.Array = field(init=False, repr=False)
    t_mesh: jax.Array = field(init=False, repr=False)
    u0: float = field(init=False, repr=False)
    uL: float = field(init=False, repr=False)
    u_IC_fun: Callable = field(init=False, repr=False)
    u_IC: float | jax.Array = field(init=False, repr=False)
    
    # being a POST-init, this is called only after __init__() has been called
    # (which happens when the class is instantiated)
    def __post_init__(self, mesh):
        # (if not empty dict)
        if mesh:
            # SPACE MESH
            # HACK: assuming uniform spacing in time and space
            self.x_mesh = jnp.ravel(jnp.asarray(mesh['x']))
            # shape is (Nx, ) or, at most, (Nx, 1) => size (total number of elements)
            # is Nx either way
            self.Nx = self.x_mesh.size
            dx = jnp.diff(self.x_mesh)
            if not jnp.all(jnp.isclose(dx, dx[0])):
                raise ValueError('Only uniform space grids are supported')
            self.dx = dx[0]
            
            # TIME MESH
            self.t_mesh = jnp.ravel(jnp.asarray(mesh['t']))
            self.Nt = self.t_mesh.size
            if self.STEADY is None:
                # to have a more general solver, steady problems still have a time mesh
                # (and solutions have shape (Nt,Nx), i.e. (1,Nx), rather than (Nx,))
                # but with only 1 time instant, t = 0
                self.STEADY = (self.Nt == 1)
            if self.STEADY and self.Nt != 1:
                raise ValueError('Steady problems require exactly ONE time instant (e.g. t = 0)')
            if not self.STEADY and self.Nt < 2:
                raise ValueError('Unsteady problems require at least TWO time instants')
            if not self.STEADY:
                dt = jnp.diff(self.t_mesh)
                if not jnp.all(jnp.isclose(dt, dt[0])):
                    raise ValueError('Only uniform space grids are supported')
                self.dt = dt[0]
                self.T = self.t_mesh[-1] - self.t_mesh[0]
            else:
                # problem treated as steady => set dt to None
                self.dt = None
                self.T = None
        
        # BOUNDARY CONDITIONS
        self.u0 = self.BC['u0']
        self.uL = self.BC['uL']
        self.u_IC_fun = self.BC['u_IC']
        if self.STEADY:
            self.u_IC = None
        else:
            # numerical discretisation of u0
            self.u_IC = jnp.asarray(self.u_IC_fun(self.x_mesh))
    
    # pack various data into the tuple required by the solver, in the order
    # required by the solver
    def solver_args(self, beta_fun):
        return (beta_fun, self.nu_baseline, self.x_mesh, self.t_mesh,
                self.u_IC, self.u0, self.uL, self.STEADY)

@dataclass
class _Solution:
    x: jax.Array
    t: jax.Array
    solution: jax.Array
    beta: jax.Array | None = None
    
    # not needed "per se", but makes sure that they're all JAX arrays
    def __post_init__(self):
        # make sure they have shape (N, ), not (N, 1) or (1, N)
        self.x = jnp.ravel(jnp.asarray(self.x))
        self.t = jnp.ravel(jnp.asarray(self.t))
        self.solution = jnp.asarray(self.solution)
        if self.beta is not None:
            self.beta = jnp.asarray(self.beta)
            if self.beta.shape != (self.x.size, self.t.size):
                aux.warning('Wrong beta ordering: it should be (Nx, Nt), '
                                  'i.e. the transpose of the solution array (Nt, Nx)\n'
                                  'Reordering beta...')
                self.beta = self.beta.T
        

