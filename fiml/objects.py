from dataclasses import dataclass, InitVar, field
from typing import Callable
import jax
# use float64, rather than float32
jax.config.update('jax_enable_x64', True)
import jax.numpy as jnp
import fiml.fiml as fiml


@dataclass
class Problem:
    # mark it as a dictionary that will be unpacked and read during
    # initialisation, but not stored in the class => avoid unadvertedly 
    # modyfing the data in the dicionary
    #   Problem.x_mesh      => works
    #   Problem.mesh        => error (AttributeError)
    mesh: InitVar[dict]
    BC: dict
    nu: Callable
    solver_fun: Callable
    
    # defined DERIVED ATTRIBUTES: they're not supplied by the user to the
    # constructor, but calculated by the class
    #   init=False      not automatically generated by __init__()
    #   repr=False      no automatic string representation of the object
    #                   (as the mesh could be very big)
    x_mesh: jax.Array = field(init=False, repr=False)
    x_mesh: jax.Array = field(init=False, repr=False)
    u0: float = field(init=False, repr=False)
    uL: float = field(init=False, repr=False)
    u_IC_fun: Callable = field(init=False, repr=False)
    u_IC: float | jax.Array = field(init=False, repr=False)
    STEADY: bool = field(init=False)
    
    # being a POST-init, this is called only after __init__() has been called
    # (which happens when the class is instantiated)
    def __post_init__(self, mesh):
        # make sure once and for all they're JAX arrays
        self.x_mesh = jnp.asarray(mesh['x'])
        self.t_mesh = jnp.asarray(mesh['t'])
        self.u0 = self.BC['u0']
        self.uL = self.BC['uL']
        self.u_IC_fun = self.BC['u_IC']
        # to have a more general solver, steady problems still have a time mesh
        # (and solutions have shape (Nt,Nx), i.e. (1,Nx), rather than (Nx,))
        # but with only 1 time instant, t = 0
        self.STEADY = True if self.t_mesh.size == 1 else False
        if self.STEADY:
            self.u_IC = None
        else:
            # numerical discretisation of u0
            self.u_IC = jnp.asarray(self.u_IC_fun(self.x_mesh))
    
    # pack various data into the tuple required by the solver, in the order
    # required by the solver
    def solver_args(self, beta_fun):
        return (beta_fun, self.nu, self.x_mesh, self.t_mesh,
                self.u_IC, self.u0, self.uL, self.STEADY)


@dataclass
class MAPResult:
    theta: float | jax.Array
    solution: float | jax.Array
    beta: float | jax.Array
    max_res: float | jax.Array
    success: bool | jax.Array
    opt: dict
    H: jax.Array = None
    covariance: float | jax.Array = None


@dataclass
class SamplingResult:
    theta: float | jax.Array
    solution: float | jax.Array
    beta: float | jax.Array
    max_res: float | jax.Array
    success: bool | jax.Array


@dataclass
class CostFunction:
    data: jax.Array
    h_theta: Callable
    C_data: float | jax.Array
    C_theta: float | jax.Array
    theta_prior: float | jax.Array

    def __call__(self, theta):
        return fiml.cost_function(theta, d=self.data, h_theta=self.h_theta,
                                  Cm=self.C_data, C_theta=self.C_theta,
                                  theta_prior=self.theta_prior)


@dataclass
class FieldInversionObject:
    problem: Problem
    exp_data: dict
    beta_fun: Callable
    beta_params: dict
    beta_opts: dict

    cost: CostFunction | None = None
    MAP: MAPResult | None = None
    prior: SamplingResult | None = None
    posterior: SamplingResult | None = None

